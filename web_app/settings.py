def normalize_domain_entry(value):
    candidate = value.strip()
    if not candidate:
        return ""

    if "://" in candidate:
        parsed = urlparse(candidate)
        candidate = parsed.netloc or parsed.path

    return candidate.split(":", 1)[0].lower().strip("/")


def csv_domains(value):
    return [
        normalized
        for item in value.split(",")
        if (normalized := normalize_domain_entry(item))
    ]


def telegram_auth_bots(value):
    value = value.strip()
    if not value:
        return {}

    if value.startswith("{"):
        parsed = json.loads(value)
        bots = {}
        for domain, bot in parsed.items():
            normalized_domain = normalize_domain_entry(domain)
            username = str(bot.get("username", "")).strip().lstrip("@")
            token = str(bot.get("token", "")).strip()
            if normalized_domain and username and token:
                bots[normalized_domain] = {
                    "username": username,
                    "token": token,
                }
        return bots

    bots = {}
    for item in value.split(","):
        if not item.strip():
            continue

        parts = [part.strip() for part in item.split("|", 2)]
        if len(parts) != 3:
            raise ValueError(
                "TELEGRAM_AUTH_BOTS entries must use "
                "domain|bot_username|bot_token format"
            )

        domain, username, token = parts
        normalized_domain = normalize_domain_entry(domain)
        username = username.lstrip("@")
        if normalized_domain and username and token:
            bots[normalized_domain] = {
                "username": username,
                "token": token,
            }

    return bots


def telegram_web_login_start_codes(value):
    value = value.strip()
    if not value:
        return {}

    codes = {}
    for item in value.split(","):
        if not item.strip():
            continue

        parts = [part.strip() for part in item.split("|", 1)]
        if len(parts) != 2:
            raise ValueError(
                "TELEGRAM_WEB_LOGIN_START_CODES entries must use "
                "domain|webvN or webvN|domain format"
            )

        left, right = parts
        left_is_code = left.lower().startswith("web")
        right_is_code = right.lower().startswith("web")
        if left_is_code == right_is_code:
            raise ValueError(
                "TELEGRAM_WEB_LOGIN_START_CODES entries must contain one domain "
                "and one web start code"
            )

        if left_is_code:
            code, domain = left, right
        else:
            domain, code = left, right

        normalized_domain = normalize_domain_entry(domain)
        normalized_code = code.lower()
        if normalized_domain and normalized_code:
            codes[normalized_domain] = normalized_code

    return codes


